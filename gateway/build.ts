import fs from "node:fs";
import path from "node:path";

const GATEWAY_DIR = import.meta.dir;
const ROOT_DIR = path.resolve(GATEWAY_DIR, "..");
const FRONTEND_DIR = path.join(ROOT_DIR, "frontend");
const PUBLIC_DIR = path.join(GATEWAY_DIR, "public");
const ASSETS_DIR = path.join(PUBLIC_DIR, "assets");
const EMBEDDED_PATH = path.join(GATEWAY_DIR, "embeddedAssets.ts");

function minifyCss(css: string): string {
  return css
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .replace(/\s+/g, " ")
    .replace(/\s*([{}:;,>~])\s*/g, "$1")
    .replace(/;}/g, "}")
    .trim();
}

function minifyHtml(html: string): string {
  return html
    .replace(/<!--[\s\S]*?-->/g, "")
    .replace(/>\s+</g, "><")
    .replace(/\s{2,}/g, " ")
    .trim();
}

export async function buildFrontendAssets(): Promise<{
  indexHtml: string;
  stylesCss: string;
  appJs: string;
}> {
  fs.rmSync(PUBLIC_DIR, { recursive: true, force: true });
  fs.mkdirSync(ASSETS_DIR, { recursive: true });

  const jsEntry = path.join(FRONTEND_DIR, "app.ts");
  const buildResult = await Bun.build({
    entrypoints: [jsEntry],
    outdir: ASSETS_DIR,
    target: "browser",
    format: "esm",
    minify: true,
    sourcemap: "none",
    naming: "app.js",
  });

  if (!buildResult.success) {
    const details = buildResult.logs.map((l) => l.message).join("\n");
    throw new Error(`Frontend TypeScript bundle failed:\n${details}`);
  }

  const appJsPath = path.join(ASSETS_DIR, "app.js");
  const appJs = fs.readFileSync(appJsPath, "utf-8");

  const rawCss = fs.readFileSync(path.join(FRONTEND_DIR, "styles.css"), "utf-8");
  const stylesCss = minifyCss(rawCss);
  fs.writeFileSync(path.join(ASSETS_DIR, "styles.css"), stylesCss, "utf-8");

  const rawHtml = fs.readFileSync(path.join(FRONTEND_DIR, "index.html"), "utf-8");
  const indexHtml = minifyHtml(rawHtml);
  fs.writeFileSync(path.join(PUBLIC_DIR, "index.html"), indexHtml, "utf-8");

  const embeddedSource =
    `// Auto-generated by gateway/build.ts — minified, sourcemap-free client bundle.\n` +
    `export const EMBEDDED_INDEX_HTML = ${JSON.stringify(indexHtml)};\n` +
    `export const EMBEDDED_STYLES_CSS = ${JSON.stringify(stylesCss)};\n` +
    `export const EMBEDDED_APP_JS = ${JSON.stringify(appJs)};\n`;

  fs.writeFileSync(EMBEDDED_PATH, embeddedSource, "utf-8");

  return { indexHtml, stylesCss, appJs };
}

if (import.meta.main) {
  const res = await buildFrontendAssets();
  console.log(
    `[Gateway-Build] Bundled UI without sourcemaps: index.html (${res.indexHtml.length}B), ` +
      `styles.css (${res.stylesCss.length}B), app.js (${res.appJs.length}B)`
  );
}
